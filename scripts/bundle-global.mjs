/**
 * Builds packages/ui/dist/arh.global.jsx — every package concatenated into one
 * browser-loadable file for the review page and for any surface that cannot run
 * a bundler (a Slidev deck, a static docs page, a CodePen).
 *
 *   node scripts/bundle-global.mjs
 *
 * Each package is wrapped in its own IIFE and publishes only its exports, so
 * package-private helpers (num, nice, GRID, backdrop, FOCUSABLE…) cannot collide
 * as packages are added. Dependency order is the order of PACKAGES below, which
 * is the same order as the table in packages/README.md.
 */
import { readFile, writeFile } from "node:fs/promises";

const PACKAGES = [
  "icons", "ui", "motion", "prose", "contracts", "table",
  "filters", "patterns", "forms", "shell", "charts", "slides"
];
const OUT = "packages/ui/dist/arh.global.jsx";

const strip = src => src
  .replace(/^"use client";$/m, "")
  .replace(/^import [\s\S]*?from "[^"]+";$/gm, "")
  .replace(/^export \{ [^}]+ \};?$/gm, "")
  .replace(/export (function|const) /g, "$1 ");

const published = [];
const blocks = [];

for (const name of PACKAGES) {
  const src = await readFile(`packages/${name}/src/index.jsx`, "utf8");
  const exports = [...new Set([...src.matchAll(/export (?:function|const) (\w+)/g)].map(m => m[1]))];
  const body = strip(src);
  const deps = published.filter(d => !exports.includes(d) && new RegExp(`\\b${d}\\b`).test(body));
  blocks.push(`/* ── @al-rayhaanat/${name} ── */
Object.assign(__ARH, (() => {
${deps.length ? `  const { ${deps.join(", ")} } = __ARH;\n` : ""}${body}
  return { ${exports.join(", ")} };
})());
`);
  published.push(...exports.filter(e => !published.includes(e)));
}

await writeFile(OUT, `/* GENERATED by scripts/bundle-global.mjs — do not edit. */
const { useState, useRef, useMemo, useEffect, useCallback, createContext, useContext, useId } = React;
const __ARH = {};

${blocks.join("\n")}
window.ARH = __ARH;
`);
console.log(`${OUT}: ${PACKAGES.length} packages, ${published.length} exports`);
